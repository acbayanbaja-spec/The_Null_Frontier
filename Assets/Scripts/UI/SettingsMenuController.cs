using System.Collections.Generic;
using NullFrontier.Core;
using NullFrontier.Player;
using UnityEngine;
using UnityEngine.Rendering.Universal;
using UnityEngine.UI;

namespace NullFrontier.UI
{
    /// <summary>
    /// Settings screen. Every row is a real control: quality tier, frame-rate cap and
    /// render scale change the URP pipeline, the sensitivity slider drives the camera
    /// rig, and the three volume sliders drive the procedural mix. Choices are written
    /// into the save file and re-applied on the next launch.
    ///
    /// Built from buttons and sliders rather than dropdowns so the whole screen can be
    /// generated by script - a Dropdown needs a templated item list that is not worth
    /// hand-building at runtime.
    /// </summary>
    public class SettingsMenuController : MonoBehaviour
    {
        [Header("Graphics")]
        [SerializeField] private Button qualityCycle;
        [SerializeField] private Button frameRateCycle;
        [SerializeField] private Slider resolutionScale;

        [Header("Controls")]
        [SerializeField] private Slider lookSensitivity;

        [Header("Audio")]
        [SerializeField] private Slider masterVolume;
        [SerializeField] private Slider ambientVolume;
        [SerializeField] private Slider effectsVolume;

        [Header("Actions")]
        [SerializeField] private Button resetButton;

        private static readonly int[] FrameRateOptions = { 30, 60, 120, 0 };

        /// <summary>One slider plus how to apply it and how to print it.</summary>
        private class Row
        {
            public Slider Slider;
            public Text Label;
            public System.Action<float> Apply;
            public System.Func<float, string> Display;
        }

        private readonly List<Row> _rows = new();
        private int _frameRateIndex = 1;

        private void Start()
        {
            var settings = SaveSystem.Instance?.Data?.settings;
            ApplyLoaded(settings);
            BuildRows(settings);
        }

        private void ApplyLoaded(SaveSystem.SettingsData settings)
        {
            if (settings == null) return;

            if (settings.qualityLevel >= 0 && settings.qualityLevel < QualitySettings.names.Length)
                QualitySettings.SetQualityLevel(settings.qualityLevel, applyExpensiveChanges: false);
            SetRenderScale(settings.renderScale);
            if (settings.targetFrameRate > 0) Application.targetFrameRate = settings.targetFrameRate;
            PlayerCameraController.LookSensitivity = Mathf.Clamp(settings.lookSensitivity, 0.2f, 3f);

            var audio = AudioDirector.Instance;
            if (audio != null)
            {
                audio.SetMasterVolume(settings.masterVolume);
                audio.SetAmbientVolume(settings.ambientVolume);
                audio.SetEffectsVolume(settings.effectsVolume);
            }
        }

        private void BuildRows(SaveSystem.SettingsData settings)
        {
            if (qualityCycle != null)
            {
                if (QualitySettings.names.Length == 0) qualityCycle.interactable = false;
                else
                {
                    Show(qualityCycle, QualitySettings.names[QualitySettings.GetQualityLevel()]);
                    qualityCycle.onClick.AddListener(CycleQuality);
                }
            }

            if (frameRateCycle != null)
            {
                _frameRateIndex = IndexOfFrameRate(Application.targetFrameRate);
                Show(frameRateCycle, FrameRateLabel(_frameRateIndex));
                frameRateCycle.onClick.AddListener(CycleFrameRate);
            }

            Add(resolutionScale, 0.5f, 1f, settings != null ? settings.renderScale : 1f,
                v => { SetRenderScale(v); Commit(); }, v => $"{v:F2}x");

            Add(lookSensitivity, 0.2f, 3f,
                settings != null ? settings.lookSensitivity : PlayerCameraController.LookSensitivity,
                v => { PlayerCameraController.LookSensitivity = v; Commit(); }, v => $"{v:F1}x");

            Add(masterVolume, 0f, 1f, settings != null ? settings.masterVolume : 0.75f,
                v => { AudioDirector.Instance?.SetMasterVolume(v); Commit(); }, Percent);
            Add(ambientVolume, 0f, 1f, settings != null ? settings.ambientVolume : 0.28f,
                v => { AudioDirector.Instance?.SetAmbientVolume(v); Commit(); }, Percent);
            Add(effectsVolume, 0f, 1f, settings != null ? settings.effectsVolume : 1f,
                v => { AudioDirector.Instance?.SetEffectsVolume(v); Commit(); }, Percent);

            if (resetButton != null) resetButton.onClick.AddListener(ResetDefaults);
        }

        private void Add(Slider slider, float min, float max, float start,
            System.Action<float> apply, System.Func<float, string> display)
        {
            if (slider == null) return;
            slider.minValue = min;
            slider.maxValue = max;
            slider.wholeNumbers = false;

            var row = new Row
            {
                Slider = slider,
                Label = slider.GetComponentInChildren<Text>(),
                Apply = apply,
                Display = display
            };
            _rows.Add(row);

            // Seed before listening: loading the screen must not count as an edit.
            slider.SetValueWithoutNotify(Mathf.Clamp(start, min, max));
            slider.onValueChanged.AddListener(v =>
            {
                if (row.Label != null) row.Label.text = row.Display(v);
                apply(v);
            });
            if (row.Label != null) row.Label.text = display(slider.value);
        }

        private void CycleQuality()
        {
            int next = (QualitySettings.GetQualityLevel() + 1) % QualitySettings.names.Length;
            QualitySettings.SetQualityLevel(next, applyExpensiveChanges: true);
            Show(qualityCycle, QualitySettings.names[next]);
            Commit();
        }

        private void CycleFrameRate()
        {
            _frameRateIndex = (_frameRateIndex + 1) % FrameRateOptions.Length;
            int rate = FrameRateOptions[_frameRateIndex];
            Application.targetFrameRate = rate;   // 0 hands the cap back to the driver
            Show(frameRateCycle, FrameRateLabel(_frameRateIndex));
            Commit();
        }

        /// <summary>Shipped defaults, keyed by the slider GameObject the builder names.</summary>
        private static readonly Dictionary<string, float> Defaults = new()
        {
            { "Resolution", 1f }, { "Sensitivity", 1f },
            { "Master", 0.75f }, { "Ambient", 0.28f }, { "Effects", 1f }
        };

        /// <summary>Restore the shipped defaults and push them through to every system.</summary>
        private void ResetDefaults()
        {
            foreach (var row in _rows)
            {
                if (!Defaults.TryGetValue(row.Slider.gameObject.name, out float value)) continue;
                value = Mathf.Clamp(value, row.Slider.minValue, row.Slider.maxValue);
                row.Slider.SetValueWithoutNotify(value);
                if (row.Label != null) row.Label.text = row.Display(value);
                row.Apply(value);
            }
            Commit();
        }

        private static string Percent(float v) => $"{Mathf.RoundToInt(v * 100f)}%";

        private static void SetRenderScale(float scale)
        {
            if (QualitySettings.renderPipeline is UniversalRenderPipelineAsset urp)
                urp.renderScale = Mathf.Clamp(scale, 0.5f, 1f);
        }

        private static float CurrentRenderScale() =>
            QualitySettings.renderPipeline is UniversalRenderPipelineAsset urp ? urp.renderScale : 1f;

        private static int IndexOfFrameRate(int rate)
        {
            for (int i = 0; i < FrameRateOptions.Length; i++)
                if (FrameRateOptions[i] == rate) return i;
            return 1;
        }

        private static string FrameRateLabel(int index)
        {
            int rate = FrameRateOptions[index];
            return rate > 0 ? $"{rate} FPS" : "UNLIMITED";
        }

        private static void Show(Button button, string text)
        {
            if (button == null) return;
            var label = button.GetComponentInChildren<Text>();
            if (label != null) label.text = text;
        }

        /// <summary>Write the live values into the save and ask for a debounced write.</summary>
        private static void Commit()
        {
            var save = SaveSystem.Instance;
            if (save == null || save.Data == null) return;

            var settings = save.Data.settings ??= new SaveSystem.SettingsData();
            settings.qualityLevel = QualitySettings.GetQualityLevel();
            settings.targetFrameRate = Application.targetFrameRate;
            settings.renderScale = CurrentRenderScale();
            settings.lookSensitivity = PlayerCameraController.LookSensitivity;

            var audio = AudioDirector.Instance;
            if (audio != null)
            {
                settings.masterVolume = audio.MasterLevel;
                settings.ambientVolume = audio.AmbientLevel;
                settings.effectsVolume = audio.EffectsLevel;
            }
            GameEvents.RaiseSaveRequested();
        }
    }
}
