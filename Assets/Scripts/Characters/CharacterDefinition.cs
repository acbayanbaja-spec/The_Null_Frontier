using System.Collections.Generic;
using UnityEngine;

namespace NullFrontier.Characters
{
    /// <summary>
    /// Immutable character definition. The roster is defined in code (not asset files)
    /// so it works without any imported art; swap in modelPrefab/avatar references as
    /// production assets arrive. Character identities come from the established roster:
    /// Jahred (iidreuspade), Angel (andi), John Steve (igris), Joyce (joy),
    /// Jessel Mae (ursula). A sixth roster slot did not exist in any prior project
    /// files (the workspace was empty), so "Vince (vanta)" is an original addition.
    /// </summary>
    public class CharacterDefinition
    {
        public string Id;
        public string DisplayName;
        public string Role;
        public string AbilityId;
        public string Description;
        public float MaxHealth;
        public float MaxStamina;
        public float MaxShield;
        public float MoveSpeed;
        public float AttackMultiplier;
        public float DefenseMultiplier;
        public Color AccentColor;

        /// <summary>
        /// Model resource name under Resources/Characters (generated by the scene
        /// builder from the Quaternius pack). Empty means "keep whatever visual is
        /// already on the rig" - the code never requires art to exist.
        /// </summary>
        public string ModelPrefab = "";

        public CharacterDefinition(string id, string displayName, string role, string abilityId,
            string description, float maxHealth, float maxStamina, float maxShield,
            float moveSpeed, float attackMultiplier, float defenseMultiplier, Color accentColor,
            string modelPrefab)
        {
            Id = id;
            DisplayName = displayName;
            Role = role;
            AbilityId = abilityId;
            Description = description;
            MaxHealth = maxHealth;
            MaxStamina = maxStamina;
            MaxShield = maxShield;
            MoveSpeed = moveSpeed;
            AttackMultiplier = attackMultiplier;
            DefenseMultiplier = defenseMultiplier;
            AccentColor = accentColor;
            ModelPrefab = modelPrefab;
        }
    }

    public static class CharacterRegistry
    {
        public static readonly IReadOnlyList<CharacterDefinition> All = new List<CharacterDefinition>
        {
            new("iidreuspade", "Jahred", "Vanguard", "tactical_dash",
                "Balanced front-line explorer. Reliable in every situation.", 110f, 100f, 30f, 5.2f, 1.0f, 1.0f,
                new Color(0.2f, 0.7f, 1f), "Soldier_Male"),
            new("andi", "Angel", "Infiltrator", "holographic_decoy",
                "Fast and elusive. Excels at stealth and hit-and-run combat.", 85f, 130f, 20f, 6.0f, 0.95f, 0.85f,
                new Color(1f, 0.4f, 0.8f), "Ninja_Female"),
            new("igris", "John Steve", "Heavy", "energy_shield",
                "Slow but durable. Wears heavy armor and anchors any firefight.", 150f, 85f, 60f, 4.6f, 1.1f, 1.25f,
                new Color(1f, 0.7f, 0.1f), "Knight_Male"),
            new("joy", "Joyce", "Scout", "enhanced_scanning",
                "Marksman and pathfinder. Sees threats before they see her.", 90f, 115f, 25f, 5.6f, 1.15f, 0.9f,
                new Color(0.4f, 1f, 0.6f), "Casual_Female"),
            new("ursula", "Jessel Mae", "Technomancer", "emp_pulse",
                "Weaponizes the Frontier itself. Abilities disrupt enemy systems.", 95f, 100f, 40f, 5.0f, 1.05f, 1.0f,
                new Color(0.7f, 0.4f, 1f), "Witch"),
            new("vanta", "Vince", "Reaper", "temp_overdrive",
                "Close-range specialist. Original sixth roster member.", 100f, 110f, 25f, 5.4f, 1.2f, 0.95f,
                new Color(0.9f, 0.15f, 0.2f), "Ninja_Male"),
        };

        public static CharacterDefinition Get(string id)
        {
            for (int i = 0; i < All.Count; i++)
            {
                if (All[i].Id == id) return All[i];
            }
            return All[0]; // fallback: protagonist
        }
    }
}
